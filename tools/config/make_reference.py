#!/usr/bin/env python3
"""Render the settings reference page from the schema.

    idf.py reconfigure
    tools/config/espdrone_config.py schema -o /tmp/schema.json
    tools/config/make_reference.py /tmp/schema.json > docs/handbook/configuration-reference.md

The page lists every symbol of "ESPDrone Config" with its title, default and range, so it never
drifts from main/Kconfig.projbuild. Values shown are those of the configuration the schema came from.
"""
import json
import sys

HEADER = """# Configuration reference

Every setting of **ESPDrone Config**, as exported by `tools/config/espdrone_config.py`. For how to change
them see [Configuration](configuration.md).

> Generated by `tools/config/make_reference.py` from the default configuration. Do not edit by hand,
> regenerate it after changing `main/Kconfig.projbuild`. A dash means the setting only exists when
> something else is enabled. The help text of each setting is in `menuconfig` (press `?`).

"""


def fmt(value):
    if isinstance(value, bool):
        return 'on' if value else 'off'
    if value in ('', None):
        return '-'
    return '`%s`' % value


def rows(entry):
    out = []
    for item in entry.get('items', []):
        if item['type'] == 'menu':
            out.append(('menu', item))
        elif item['type'] == 'choice':
            choices = ', '.join(c['title'] for c in item['choices'])
            out.append(('row', item['name'], '%s (one of: %s)' % (item['title'], choices),
                        fmt(next((c['title'] for c in item['choices'] if c['name'] == item['value']), None)), ''))
        elif item.get('name'):
            rng = '%s to %s' % tuple(item['range']) if item.get('range') else ''
            out.append(('row', item['name'], item['title'], fmt(item['value']), rng))
            out.extend(rows(item))
    return out


def emit(entry, level, out):
    found = rows(entry)
    plain = [r for r in found if r[0] == 'row']
    if plain:
        out.append('| Symbol | Setting | Default | Range |')
        out.append('|---|---|---|---|')
        for _, name, title, default, rng in plain:
            out.append('| `%s` | %s | %s | %s |' % (name, title, default, rng))
        out.append('')
    for r in found:
        if r[0] == 'menu':
            out.append('%s %s\n' % ('#' * level, r[1]['title']))
            emit(r[1], level + 1, out)


def main():
    with open(sys.argv[1]) as f:
        schema = json.load(f)
    out = [HEADER]
    for group in schema['items']:
        if group['type'] == 'menu':
            out.append('## %s\n' % group['title'])
            emit(group, 3, out)
    sys.stdout.write('\n'.join(out).rstrip() + '\n')


if __name__ == '__main__':
    main()
