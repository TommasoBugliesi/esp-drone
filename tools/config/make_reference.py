#!/usr/bin/env python3
"""Render the settings reference page from the schema.

    idf.py -B build-v1 -D IDF_TARGET=esp32 reconfigure
    idf.py -B build-v2 -D IDF_TARGET=esp32s3 reconfigure
    tools/config/espdrone_config.py schema -b build-v1 -o /tmp/v1.json
    tools/config/espdrone_config.py schema -b build-v2 -o /tmp/v2.json
    tools/config/make_reference.py /tmp/v1.json /tmp/v2.json > docs/handbook/configuration-reference.md

The page lists every symbol of "ESPDrone Config" with its title, default and range, so it never
drifts from main/Kconfig.projbuild. With two schemas (FlyingFree V1.0 and V2) it shows the default
of each board; with one, the defaults of that configuration.
"""
import json
import sys

HEADER = """# Configuration reference

Every setting of **ESPDrone Config**, as exported by `tools/config/espdrone_config.py`. For how to change
them see [Configuration](configuration.md).

> Generated by `tools/config/make_reference.py` from the default configuration of each board. Do not edit by hand,
> regenerate it after changing `main/Kconfig.projbuild`. A dash means the setting only exists when
> something else is enabled. The help text of each setting is in `menuconfig` (press `?`).

"""


def fmt(value):
    if isinstance(value, bool):
        return 'on' if value else 'off'
    if value in ('', None):
        return '-'
    return '`%s`' % value


def rows(entry):
    out = []
    for item in entry.get('items', []):
        if item['type'] == 'menu':
            out.append(('menu', item))
        elif item['type'] == 'choice':
            choices = ', '.join(c['title'] for c in item['choices'])
            out.append(('row', item['name'], '%s (one of: %s)' % (item['title'], choices),
                        fmt(next((c['title'] for c in item['choices'] if c['name'] == item['value']), None)), ''))
        elif item.get('name'):
            rng = '%s to %s' % tuple(item['range']) if item.get('range') else ''
            out.append(('row', item['name'], item['title'], fmt(item['value']), rng))
            out.extend(rows(item))
    return out


def defaults_by_name(entry, found=None):
    """Symbol name -> formatted default, for the second board's column."""
    found = {} if found is None else found
    for kind, *rest in rows(entry):
        if kind == 'row':
            found[rest[0]] = (rest[2], rest[3])
        else:
            defaults_by_name(rest[0], found)
    return found


def emit(entry, level, out, other):
    found = rows(entry)
    plain = [r for r in found if r[0] == 'row']
    if plain:
        if other is None:
            out.append('| Symbol | Setting | Default | Range |')
            out.append('|---|---|---|---|')
        else:
            out.append('| Symbol | Setting | V1.0 default | V2 default | Range |')
            out.append('|---|---|---|---|---|')
        for _, name, title, default, rng in plain:
            if other is None:
                out.append('| `%s` | %s | %s | %s |' % (name, title, default, rng))
            else:
                other_default, other_rng = other.get(name, ('-', ''))
                if other_rng != rng:
                    rng = '%s (V1.0), %s (V2)' % (rng or '-', other_rng or '-')
                out.append('| `%s` | %s | %s | %s | %s |' % (name, title, default, other_default, rng))
        out.append('')
    for r in found:
        if r[0] == 'menu':
            out.append('%s %s\n' % ('#' * level, r[1]['title']))
            emit(r[1], level + 1, out, other)


def main():
    with open(sys.argv[1]) as f:
        schema = json.load(f)
    other = None
    if len(sys.argv) > 2:
        with open(sys.argv[2]) as f:
            other = defaults_by_name(json.load(f))
    out = [HEADER]
    for group in schema['items']:
        if group['type'] == 'menu':
            out.append('## %s\n' % group['title'])
            emit(group, 3, out, other)
    sys.stdout.write('\n'.join(out).rstrip() + '\n')


if __name__ == '__main__':
    main()
